"""Generate an always-fresh CLAUDE.md / .cursorrules from the FalkorDB graph.

Solves the documented pain: flat agent-rules files rot and have a manual upkeep
tax. Here the file is regenerated from the live graph  team rules, the chokepoints
to edit carefully, code ownership, and API entrypoints  so an AI agent's base
context is never stale.

    python -m app.genrules --project proj_myrepo --format claude > CLAUDE.md
"""
import argparse


def build(client, fmt="claude"):
    rules = client.all_rules()
    chokes = client.centrality(limit=5)
    # ownership per file
    own = client.run("""MATCH (d:Developer)-[a:AUTHORED]->(f:File)
                        RETURN f.path, d.name, a.commits ORDER BY a.commits DESC""").result_set
    owners = {}
    for path, dev, commits in own:
        owners.setdefault(path, (dev, commits))
    # endpoints
    eps = client.run("""MATCH (e:Endpoint)-[:EXECUTES]->(fn:Function)
                        RETURN e.method, e.route, fn.name ORDER BY e.route""").result_set

    L = []
    title = "# Project rules for AI agents (auto-generated by ContextAnchor)"
    L.append(title)
    L.append("_Regenerate with `python -m app.genrules`  do not edit by hand; the graph is the source of truth._\n")

    L.append("## Hard rules (do not violate)")
    if rules:
        for r in rules:
            tg = ", ".join(t["name"] for t in r.get("targets", [])) or "repo-wide"
            L.append(f"- **[{r['severity']}] {r['id']}** — {r['rule']}  _(applies to: {tg})_")
    else:
        L.append("- (none recorded yet)")

    L.append("\n## Edit these with extra care (high blast-radius chokepoints)")
    if chokes:
        for c in chokes:
            L.append(f"- `{c['function']}()` in `{c['file']}` — centrality {c['score']}")
    else:
        L.append("- (no graph loaded)")

    L.append("\n## Code ownership (ask / tag before large changes)")
    if owners:
        for path, (dev, commits) in list(owners.items())[:20]:
            L.append(f"- `{path}` → {dev} ({commits} commits)")
    else:
        L.append("- (no git history ingested)")

    if eps:
        L.append("\n## Public API entrypoints (changing these breaks callers)")
        for method, route, fn in eps:
            L.append(f"- `{method} {route}` → `{fn}()`")

    L.append("\n## Before changing any function")
    L.append("Query ContextAnchor (MCP tool `analyze_change`, or `python -m app.check <fn>`) "
             "to get its blast radius, governing rules and owner. Do not refactor a chokepoint "
             "without checking downstream callers first.")
    return "\n".join(L) + "\n"


if __name__ == "__main__":
    from app.falkor_client import FalkorClient, DEFAULT_GRAPH, slug
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", default="")
    ap.add_argument("--format", default="claude", choices=["claude", "cursor"])
    args = ap.parse_args()
    c = FalkorClient()
    if args.project:
        c.use(args.project if (args.project.startswith("proj_") or args.project == DEFAULT_GRAPH) else "proj_" + slug(args.project))
    else:
        repos = [p for p in c.list_projects() if p.get("kind") != "sample"]
        c.use(repos[-1]["graph"] if repos else DEFAULT_GRAPH)
    print(build(c, args.format))
